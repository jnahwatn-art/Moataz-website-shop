const langSwitch = document.getElementById("langSwitch");
const themeSwitch = document.getElementById("themeSwitch");
const splash = document.getElementById("splashScreen");
const chatWindow = document.getElementById("chatWindow");
const chatOptions = document.getElementById("chatOptions");

let currentLang = "ar";
let currentTheme = "dark";

const setLanguage = (lang) => {
  currentLang = lang;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  langSwitch.textContent = lang === "ar" ? "EN" : "AR";

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (i18n[lang][key]) el.textContent = i18n[lang][key];
  });

  themeSwitch.textContent =
    currentTheme === "dark" ? i18n[lang].theme_switch : (lang === "ar" ? "داكن" : "Dark");
  renderChatOptions();
  resetAssistant();
};

const applyTheme = (theme) => {
  currentTheme = theme;
  document.documentElement.dataset.theme = theme;
  const lightLabel = i18n[currentLang].theme_switch;
  const darkLabel = currentLang === "ar" ? "داكن" : "Dark";
  themeSwitch.textContent = theme === "dark" ? lightLabel : darkLabel;
};

const resetAssistant = () => {
  chatWindow.innerHTML = `<div class="chat-msg assistant-msg">${i18n[currentLang].ai_welcome}</div>`;
};

const renderChatOptions = () => {
  chatOptions.innerHTML = "";
  aiData[currentLang].forEach((item) => {
    const btn = document.createElement("button");
    btn.className = "option-btn";
    btn.type = "button";
    btn.textContent = item.q;
    btn.addEventListener("click", () => {
      const userMsg = document.createElement("div");
      userMsg.className = "chat-msg user-msg";
      userMsg.textContent = item.q;

      const assistantMsg = document.createElement("div");
      assistantMsg.className = "chat-msg assistant-msg";
      assistantMsg.textContent = item.a;

      chatWindow.appendChild(userMsg);
      setTimeout(() => {
        chatWindow.appendChild(assistantMsg);
        chatWindow.scrollTop = chatWindow.scrollHeight;
      }, 260);
    });
    chatOptions.appendChild(btn);
  });
};

langSwitch.addEventListener("click", () => {
  setLanguage(currentLang === "ar" ? "en" : "ar");
});

themeSwitch.addEventListener("click", () => {
  const nextTheme = currentTheme === "dark" ? "light" : "dark";
  applyTheme(nextTheme);
  localStorage.setItem("theme", nextTheme);
});

const observer = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) entry.target.classList.add("active");
    });
  },
  { threshold: 0.15 }
);

document.querySelectorAll(".reveal").forEach((el) => observer.observe(el));

window.addEventListener("load", () => {
  const savedTheme = localStorage.getItem("theme");
  applyTheme(savedTheme === "light" ? "light" : "dark");
  setLanguage("ar");
  setTimeout(() => splash.classList.add("hidden"), 1700);
});
